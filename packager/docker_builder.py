import re
from typing import Optional, List, Dict
from core.schemas import DockerConfig, GenesisSpecification
from core.workspace import VirtualWorkspace


class DockerBuilder:
    """
    Synthesizes hardened, production-grade Dockerfiles, .dockerignore policies,
    and docker-compose manifests with non-root security and optimal layer caching.
    """

    def generate_dockerfile(
        self,
        workspace: VirtualWorkspace,
        config: Optional[DockerConfig] = None,
        spec: Optional[GenesisSpecification] = None
    ) -> str:
        """Generates a hardened Dockerfile optimized for Python container workloads."""
        cfg = config or DockerConfig()
        entrypoint_cmd = self._resolve_entrypoint_command(workspace, cfg, spec)
        exposed_ports = self._detect_ports(workspace, cfg)

        lines = [
            "# -------------------------------------------------------------",
            "# Haiox Genesis - Hardened Production Container Manifest",
            "# Auto-generated by Haiox Genesis Docker Builder v1.0",
            "# -------------------------------------------------------------",
            f"FROM python:{cfg.python_version} AS runtime",
            "",
            "# Prevent bytecode generation and ensure unbuffered output",
            "ENV PYTHONDONTWRITEBYTECODE=1 \\",
            "    PYTHONUNBUFFERED=1 \\",
            "    PIP_NO_CACHE_DIR=1 \\",
            "    PIP_DISABLE_PIP_VERSION_CHECK=1",
            "",
            "WORKDIR /app",
            "",
            "# Install essential runtime security utilities",
            "RUN apt-get update && apt-get install -y --no-install-recommends \\",
            "    curl \\",
            "    && rm -rf /var/lib/apt/lists/*",
            "",
            f"# Least-privilege principle: enforce non-root user execution",
            f"RUN useradd -u 10001 -m -s /bin/sh {cfg.app_user}",
            ""
        ]

        # Handle dependencies layer
        if "requirements.txt" in workspace.files:
            lines.extend([
                "# Cache dependencies in isolated layer",
                "COPY requirements.txt .",
                "RUN pip install --no-cache-dir -r requirements.txt",
                ""
            ])

        lines.extend([
            "# Copy application source tree",
            "COPY . .",
            "",
            f"# Set ownership to non-root user",
            f"RUN chown -R {cfg.app_user}:{cfg.app_user} /app",
            f"USER {cfg.app_user}",
            ""
        ])

        # Expose ports
        for port in exposed_ports:
            lines.append(f"EXPOSE {port}")

        if exposed_ports:
            lines.append("")

        # Add CMD instruction
        formatted_cmd = ", ".join(f'"{c}"' for c in entrypoint_cmd)
        lines.append(f"CMD [{formatted_cmd}]")
        lines.append("")

        return "\n".join(lines)

    def generate_dockerignore(self) -> str:
        """Returns standard security and performance .dockerignore policy."""
        return (
            "# -------------------------------------------------------------\n"
            "# Haiox Genesis - Docker Ignore Policy\n"
            "# -------------------------------------------------------------\n"
            "__pycache__\n"
            "*.py[cod]\n"
            "*$py.class\n"
            ".pytest_cache\n"
            ".coverage\n"
            "htmlcov/\n"
            ".git\n"
            ".gitignore\n"
            ".env\n"
            ".env.*\n"
            ".venv\n"
            "venv/\n"
            "env/\n"
            "*.log\n"
            ".DS_Store\n"
            "Thumbs.db\n"
            "dist/\n"
            "build/\n"
            "*.egg-info/\n"
        )

    def generate_docker_compose(
        self,
        project_name: str,
        workspace: VirtualWorkspace,
        config: Optional[DockerConfig] = None
    ) -> str:
        """Generates standard docker-compose.yml configuration."""
        cfg = config or DockerConfig()
        slug = re.sub(r'[^a-z0-9_]+', '_', project_name.lower()).strip('_') or "genesis_app"
        ports = self._detect_ports(workspace, cfg)

        ports_block = ""
        if ports:
            ports_block = "    ports:\n" + "\n".join(f'      - "{p}:{p}"' for p in ports) + "\n"

        return (
            f"version: '3.8'\n\n"
            f"services:\n"
            f"  {slug}:\n"
            f"    build:\n"
            f"      context: .\n"
            f"      dockerfile: Dockerfile\n"
            f"    image: haiox/{slug}:latest\n"
            f"    container_name: {slug}_instance\n"
            f"    restart: unless-stopped\n"
            f"{ports_block}"
            f"    environment:\n"
            f"      - PYTHONUNBUFFERED=1\n"
            f"      - LOG_LEVEL=INFO\n"
        )

    def populate_workspace(
        self,
        workspace: VirtualWorkspace,
        spec: Optional[GenesisSpecification] = None,
        config: Optional[DockerConfig] = None
    ) -> None:
        """Injects Dockerfile, .dockerignore, and docker-compose.yml directly into workspace."""
        p_name = spec.project_name if spec else "haiox_genesis_service"
        dockerfile = self.generate_dockerfile(workspace, config, spec)
        dockerignore = self.generate_dockerignore()
        compose = self.generate_docker_compose(p_name, workspace, config)

        workspace.add_file("Dockerfile", dockerfile)
        workspace.add_file(".dockerignore", dockerignore)
        workspace.add_file("docker-compose.yml", compose)

    def _resolve_entrypoint_command(
        self,
        workspace: VirtualWorkspace,
        config: DockerConfig,
        spec: Optional[GenesisSpecification] = None
    ) -> List[str]:
        """Infers the most appropriate entrypoint execution command."""
        if config.entrypoint_file:
            return ["python", config.entrypoint_file]

        files = list(workspace.files.keys())

        # Check common entrypoint candidates
        for candidate in ["main.py", "app.py", "bot.py", "cli.py", "run.py", "server.py"]:
            if candidate in files:
                # If app.py and fastapi is used, run with uvicorn
                content = workspace.files[candidate].content
                if "FastAPI" in content or "uvicorn" in content:
                    return ["uvicorn", f"{candidate.replace('.py', '')}:app", "--host", "0.0.0.0", "--port", "8000"]
                return ["python", candidate]

        # Check for any non-test python file
        for f in files:
            if f.endswith(".py") and not workspace.files[f].is_test:
                return ["python", f]

        # Default fallback
        return ["pytest", "-v"]

    def _detect_ports(
        self,
        workspace: VirtualWorkspace,
        config: DockerConfig
    ) -> List[int]:
        """Detects whether standard ports need to be exposed based on libraries used."""
        if config.exposed_ports:
            return config.exposed_ports

        ports = []
        for file_obj in workspace.files.values():
            content = file_obj.content
            if "FastAPI" in content or "uvicorn" in content:
                if 8000 not in ports:
                    ports.append(8000)
            if "Flask" in content:
                if 5000 not in ports:
                    ports.append(5000)
            if "streamlit" in content.lower():
                if 8501 not in ports:
                    ports.append(8501)

        return ports
