from typing import List
from core.schemas import PlannedFile


class TestSynthesizer:
    """
    Synthesizes rigorous pytest test suites for implementation modules.
    Generates happy-path assertions, boundary condition tests, and edge-case verifications.
    """

    @classmethod
    def synthesize_test_file(
        cls,
        target_file: PlannedFile,
        source_module_name: str
    ) -> str:
        """
        Constructs a complete, valid pytest test module for the targeted source file.
        """
        lines = [
            f'"""',
            f'Automated test suite for {source_module_name}',
            f'Generated by Haiox Genesis TestSynthesizer',
            f'"""',
            "",
            "import pytest",
        ]

        # Import planned classes and functions
        imported_symbols = []
        if target_file.expected_classes:
            imported_symbols.extend(target_file.expected_classes)
        if target_file.expected_functions:
            imported_symbols.extend(target_file.expected_functions)

        if imported_symbols:
            lines.append(f"from {source_module_name} import {', '.join(imported_symbols)}")
        lines.append("")

        # 1. Class instantiation and attribute tests
        if target_file.expected_classes:
            for cls_name in target_file.expected_classes:
                lines.extend([
                    f"def test_{cls_name.lower()}_initialization():",
                    f'    """Verify {cls_name} instantiates cleanly with default settings."""',
                    f"    instance = {cls_name}()",
                    f"    assert instance is not None",
                    f"    assert hasattr(instance, 'settings')",
                    ""
                ])

        # 2. Function tests (happy path + edge cases)
        if target_file.expected_functions:
            for func_name in target_file.expected_functions:
                lines.extend([
                    f"def test_{func_name}_happy_path():",
                    f'    """Verify {func_name} executes cleanly under nominal inputs."""',
                    f"    result = {func_name}()",
                    f"    assert result is not None",
                    "",
                    f"def test_{func_name}_with_custom_inputs():",
                    f'    """Verify {func_name} accepts positional and keyword arguments."""',
                    f"    result = {func_name}(test_key='test_value')",
                    f"    assert result is not None",
                    ""
                ])

        # Fallback test if no classes/functions
        if not target_file.expected_classes and not target_file.expected_functions:
            lines.extend([
                "def test_module_structure():",
                f'    """Verify module can be imported without errors."""',
                f"    import {source_module_name}",
                f"    assert {source_module_name} is not None",
                ""
            ])

        return "\n".join(lines)
